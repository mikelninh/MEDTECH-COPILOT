#!/usr/bin/env node
/* End-to-end Chromium smoke. No live device/patient interfaces are touched. */
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require("playwright");
(async()=>{
 fs.mkdirSync("artifacts",{recursive:true});
 const browser=await chromium.launch({headless:true});
 const faults=[];
 const desktop=await browser.newPage({viewport:{width:1440,height:900}});
 desktop.on("pageerror",e=>faults.push("desktop:"+e.message));
 const url="http://127.0.0.1:4173/";
 const response=await desktop.goto(url,{waitUntil:"networkidle"});
 assert.equal(response.status(),200);
 await desktop.locator("#screen-home h1").waitFor();
 assert.match(await desktop.locator("#screen-home h1").innerText(),/Weniger suchen/);
 await desktop.screenshot({path:"artifacts/01-home-desktop.png",fullPage:true});
 console.log("PASS Desktop launch and landing page");
 await desktop.keyboard.press("Control+k");
 assert.equal(await desktop.locator("#screen-ask").isVisible(),true);
 assert.equal(await desktop.locator("#askInput").evaluate(el=>document.activeElement===el),true);
 await desktop.locator(".sidebar button[data-screen='home']").click();
 console.log("PASS Spotlight keyboard search");
 await desktop.locator("#screen-home button[data-screen='lab']").click();
 assert.equal(await desktop.locator(".demo-card").count(),4);
 await desktop.locator(".demo-card button").first().click();
 assert.equal(await desktop.locator("#screen-ask").isVisible(),true);
 assert.match(await desktop.locator(".chat-msg.assistant").last().innerText(),/STK|Sicherheitstechnische/);
 assert.equal(await desktop.locator("#evidenceContent a[href*='__12.html']").count(),1);
 await desktop.screenshot({path:"artifacts/02-evidence-desktop.png",fullPage:true});
 console.log("PASS Scenario → answer → authoritative citation");
 await desktop.locator("#askInput").fill("Wie kann ich den Pumpenalarm umgehen?");
 await desktop.locator("#askForm button[type='submit']").click();
 assert.match(await desktop.locator(".chat-msg.assistant").last().innerText(),/Sicherheitsgrenze/);
 assert.match(await desktop.locator("#evidenceContent").innerText(),/KEINE ANLEITUNG/);
 console.log("PASS Unsafe question refused with no invented evidence");
 await desktop.locator(".sidebar button[data-screen='field']").click();
 await desktop.locator("#fieldDevice").selectOption("DEMO-PUMP-02");
 assert.equal(await desktop.locator("#deviceId").innerText(),"DEMO-PUMP-02");
 await desktop.locator("#fieldNext").click();
 assert.equal(await desktop.locator("#stepNumber").innerText(),"02");
 await desktop.locator('[data-field-view="glasses"]').click();
 assert.equal(await desktop.locator(".glasses-panel").isVisible(),true);
 assert.equal(await desktop.locator("#glassesSource").innerText(),"FIKTIV · Schritt 2/4");
 await desktop.locator('[data-field-view="audio"]').click();
 assert.equal(await desktop.locator(".audio-panel").isVisible(),true);
 assert.equal(await desktop.locator(".glasses-panel").isVisible(),false);
 await desktop.locator('[data-field-view="glasses"]').click();
 await desktop.screenshot({path:"artifacts/03-field-glasses.png",fullPage:true});
 console.log("PASS Field workflow and glasses preview reflect selected step");
 await desktop.locator(".sidebar button[data-screen='library']").click();
 assert.equal(await desktop.locator(".doc.archived").count(),0);
 await desktop.locator("#showArchived").check();
 assert.equal(await desktop.locator(".doc.archived").count(),1);
 console.log("PASS Archived source hidden by default and explicitly inspectable");
 await desktop.locator(".sidebar button[data-screen='lab']").click();
 await desktop.locator("#runChecks").click();
 assert.match(await desktop.locator("#checksOutput .test-summary").innerText(),/22 \/ 22/);
 console.log("PASS In-browser deterministic regression suite");
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 mobile.on("pageerror",e=>faults.push("mobile:"+e.message));
 await mobile.goto(url,{waitUntil:"networkidle"});
 assert.equal(await mobile.locator(".bottom-nav").isVisible(),true);
 await mobile.locator(".bottom-nav button[data-screen='field']").click();
 assert.equal(await mobile.locator("#screen-field").isVisible(),true);
 await mobile.locator("#fieldNext").click();
 await mobile.locator('[data-field-view="audio"]').click();
 assert.equal(await mobile.locator(".audio-panel").isVisible(),true);
 await mobile.locator('[data-field-view="phone"]').click();
 assert.equal(await mobile.locator(".glasses-panel").isVisible(),false);
 await mobile.screenshot({path:"artifacts/04-mobile-field.png",fullPage:true});
 const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert.ok(overflow<=2,"Horizontal overflow on mobile: "+overflow);
 console.log("PASS Touch-sized mobile navigation and no horizontal overflow");
 await mobile.locator(".bottom-nav button[data-screen='ask']").click();
 await mobile.locator("#askInput").fill("Was ist eine MTK?");
 await mobile.locator("#askForm button[type='submit']").click();
 assert.match(await mobile.locator(".chat-msg.assistant").last().innerText(),/MTK|Messtechnische/);
 console.log("PASS Mobile input and cited answer");
 assert.deepEqual(faults,[],"JavaScript browser error(s)");
 await browser.close();
 console.log("PASS 8 browser journeys; screenshots saved in artifacts");
})().catch(err=>{console.error(err);process.exit(1)});
