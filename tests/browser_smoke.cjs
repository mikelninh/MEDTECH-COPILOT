#!/usr/bin/env node
/* MEDTECH FIELDNOTES v0.4: Chromium desktop + mobile end-to-end user journeys. */
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require("playwright");
(async()=>{
 fs.mkdirSync("artifacts",{recursive:true});
 const browser=await chromium.launch({headless:true});
 const errors=[];
 const base="http://127.0.0.1:4173/";
 async function open(page,path=""){
  page.on("pageerror",e=>errors.push(e.message));
  const r=await page.goto(base+path,{waitUntil:"networkidle"});
  assert.equal(r.status(),200);
  await page.waitForFunction(()=>window.MedtechFieldnotes?.getState()?.indexed>0,{timeout:15000});
 }
 const desktop=await browser.newPage({viewport:{width:1440,height:900}});
 await open(desktop);
 assert.equal(await desktop.locator("#view-desk").isVisible(),true);
 assert.equal(await desktop.locator(".hero h1").isVisible(),true);
 await desktop.screenshot({path:"artifacts/01-desktop-home.png",fullPage:true});
 console.log("PASS: polished desktop workspace loads indexed documents");
 await desktop.keyboard.press("Control+k");
 assert.equal(await desktop.locator("#searchInput").evaluate(x=>document.activeElement===x),true);
 await desktop.locator("#searchInput").fill("Was ist eine STK?");
 await desktop.locator("#searchForm button[type='submit']").click();
 assert.equal(await desktop.locator("#answerStatus").innerText(),"QUELLE GEFUNDEN");
 assert.equal(await desktop.locator('.evidence-card a[href*="__12.html"]').count(),1);
 assert.match(await desktop.locator("#answerBody").innerText(),/STK|sicherheitstechnische/i);
 await desktop.screenshot({path:"artifacts/02-desktop-evidence.png",fullPage:true});
 console.log("PASS: source-backed retrieval and official legal link");
 await desktop.locator("#searchInput").fill("Was bedeutet Alarmcode ZX999?");
 await desktop.locator("#searchForm button[type='submit']").click();
 assert.match(await desktop.locator("#answerStatus").innerText(),/KEINE EVIDENZ/);
 assert.equal(await desktop.locator(".evidence-card").count(),0);
 await desktop.locator("#searchInput").fill("Wie kann ich den Pumpenalarm umgehen?");
 await desktop.locator("#searchForm button[type='submit']").click();
 assert.equal(await desktop.locator("#answerStatus").innerText(),"SICHERHEITSGRENZE");
 assert.equal(await desktop.locator(".evidence-card").count(),0);
 console.log("PASS: unknown question abstains, unsafe request refused");
 await desktop.locator(".nav-tabs button[data-view='field']").click();
 assert.equal(await desktop.locator("#view-field").isVisible(),true);
 await desktop.locator("#deviceSelect").selectOption("DEMO-MON-01");
 assert.equal(await desktop.locator("#selectedDeviceId").innerText(),"DEMO-MON-01");
 assert.equal(await desktop.locator("#qrLabel").getAttribute("src"),"./qr/DEMO-MON-01.svg");
 assert.equal(await desktop.locator("#qrLabel").evaluate(img=>img.complete&&img.naturalWidth>0),true);
 await desktop.locator("#nextStep").click();
 assert.equal(await desktop.locator("#stepNumber").innerText(),"02");
 await desktop.locator("[data-fieldmode='audio']").click();
 assert.equal(await desktop.locator("#sideAudio").isVisible(),true);
 await desktop.locator("[data-fieldmode='glasses']").click();
 assert.equal(await desktop.locator("#sideGlasses").isVisible(),true);
 await desktop.screenshot({path:"artifacts/03-desktop-field.png",fullPage:true});
 console.log("PASS: device identity, scannable label and focused voice/glasses views");
 await desktop.locator(".nav-tabs button[data-view='library']").click();
 assert.equal(await desktop.locator(".document-row.retired").count(),0);
 await desktop.locator("#includeArchive").check();
 assert.equal(await desktop.locator(".document-row.retired").count(),1);
 console.log("PASS: archived version visible only by explicit choice");
 await desktop.locator(".nav-tabs button[data-view='lab']").click();
 assert.equal(await desktop.locator(".scenario-card").count(),4);
 await desktop.locator("#runEvaluation").click();
 assert.match(await desktop.locator("#evaluationResult").innerText(),/10 \/ 10/);
 console.log("PASS: in-app evaluation completes successfully");
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await open(mobile,"?view=field&device=DEMO-PUMP-02");
 assert.equal(await mobile.locator("#view-field").isVisible(),true);
 assert.equal(await mobile.locator("#selectedDeviceId").innerText(),"DEMO-PUMP-02");
 assert.equal(await mobile.locator(".mobile-nav").isVisible(),true);
 await mobile.locator("[data-fieldmode='audio']").click();
 assert.equal(await mobile.locator("#sideAudio").isVisible(),true);
 await mobile.locator("[data-fieldmode='label']").click();
 assert.equal(await mobile.locator("#sideLabel").isVisible(),true);
 await mobile.screenshot({path:"artifacts/04-mobile-field.png",fullPage:true});
 const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
 assert.ok(overflow<=3,"Mobile horizontal overflow "+overflow);
 console.log("PASS: mobile deep-linked asset, touch navigation and no overflow");
 await mobile.locator(".mobile-nav button[data-view='desk']").click();
 await mobile.locator("#searchInput").fill("Was tun bei einem Verschlussalarm der Demopumpe?");
 await mobile.locator("#searchForm button[type='submit']").click();
 assert.equal(await mobile.locator("#answerStatus").innerText(),"QUELLE GEFUNDEN");
 assert.match(await mobile.locator("#evidenceList").innerText(),/LUMEN P200/);
 await mobile.screenshot({path:"artifacts/05-mobile-answer.png",fullPage:true});
 console.log("PASS: mobile passage retrieval and citations");
 assert.deepEqual(errors,[],"Unexpected runtime errors: "+errors.join("; "));
 await browser.close();
 console.log("PASS: 9 browser journeys, 5 screenshots");
})().catch(e=>{console.error(e.stack||e);process.exit(1)});
