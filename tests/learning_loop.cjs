#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict");
const Loop=require("../src/learning_loop.js");
const map=new Map();
const storage={getItem:key=>map.get(key)||null,setItem:(key,value)=>map.set(key,String(value)),removeItem:key=>map.delete(key)};
let now=1730000000000;
const l=Loop.create(storage,()=>now);
assert.equal(l.enabled(),false);
assert.equal(l.ask("mpbetreibv","Sensitive patient details are private","evidence").recorded,false);
assert.equal(map.size,0,"No storage before explicit consent");
l.consent(true);
l.faqOpen("mpbetreibv","b03");
l.ask("mpbetreibv","Wann braucht man ein Medizinproduktebuch?","evidence");
now+=18000;
const again=l.ask("mpbetreibv","Wann brauche ich ein Medizinproduktebuch?","unknown");
assert.equal(again.reask,true,"Detect very similar within-session rephrasing");
l.feedback(true);
const counts=l.stats();
assert.equal(counts.asked,2);
assert.equal(counts.reasked,1);
assert.equal(counts.faqOpens.b03,1);
assert.equal(counts.evidence,1);
assert.equal(counts.unknown,1);
assert.equal(counts.helpful,1);
const serialized=map.get(Loop.STORAGE_KEY);
assert.equal(serialized.includes("Medizinproduktebuch"),false,"Raw questions must never persist");
assert.equal(serialized.includes("patient"),false);
const restored=Loop.create(storage,()=>now).stats();
assert.equal(restored.asked,2,"Counts survive browser refresh after consent");
l.reset();
assert.equal(map.size,0,"Opt out must erase local counts and consent");
console.log("PASS: explicit consent, reask proxy, helpfulness, FAQ opens, local-only anonymous counts, erase");
